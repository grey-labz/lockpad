import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { createSandbox, ONE, STORAGE, OPERATION_STORAGE, project } from "./sandbox.mjs";

const receipts = [], checks = [];
const sandbox = await createSandbox({ onReceipt: result => receipts.push(result) });
const { accounts: { alice, bob, stranger }, pool, market, token, vault, worker, send, lock } = sandbox;
const check = (name, assertion) => { assertion(); checks.push(name); console.log("PASS:", name); };
const balance = account => token.view("ft_balance_of", { account_id: account.accountId });
const position = id => vault.view("get_position", { token_id: id });
const loan = id => pool.view("get_loan", { loan_id: id });
const accounting = () => pool.view("get_accounting", {});
const repay = (signer, id, amount) => send(signer, token, "ft_transfer_call", { receiver_id: pool.accountId, amount, msg: JSON.stringify({ action: "repay", loan_id: id }) });
const solvent = async () => {
  const a = await accounting();
  assert.equal(BigInt(await balance(pool)), BigInt(a.available_liquidity) + BigInt(a.reserved_loans) + BigInt(a.borrower_surplus) + BigInt(a.pending_withdrawals));
};
const pledge = async (signer, p, overrides = {}) => {
  const ledger = await pool.view("get_account", { account_id: signer.accountId });
  if (!ledger.loan_credits) await send(signer, pool, "prepay_loan", {}, STORAGE);
  const quote = await pool.view("get_quote", { principal: p.principal, unlock_at: p.unlock_at });
  const accepted = await send(signer, vault, "nft_transfer_call", { receiver_id: pool.accountId, token_id: p.token_id, msg: JSON.stringify({ amount: quote.maximum, principal: p.principal, unlock_at: p.unlock_at, quote_nonce: quote.quote_nonce, ...overrides }) });
  return { accepted, quote, loan: (await pool.view("get_loans_by_borrower", { borrower_id: signer.accountId, from_index: 0, limit: 100 })).find(item => item.token_id === p.token_id && item.status === "CollateralReady") };
};

try {
  const initialPoolBalance = await balance(pool), initialLiquidity = (await accounting()).available_liquidity;
  check("The lending pool starts with actual funded test tokens", () => { assert.equal(initialPoolBalance, "1000000000"); assert.equal(initialLiquidity, initialPoolBalance); });
  const unauthorizedFund = await send(bob, token, "ft_transfer_call", { receiver_id: pool.accountId, amount: "1000000", msg: JSON.stringify({ action: "fund" }) });
  check("An unauthorized funding message returns the whole transfer", () => assert.equal(unauthorizedFund.parseResult(), "0"));
  const forged = await send(stranger, pool, "ft_on_transfer", { sender_id: bob.accountId, amount: "999999999", msg: JSON.stringify({ action: "fund" }) }, "0");
  check("A forged token callback cannot create liquidity", () => assert.equal(forged.parseResult(), "999999999"));
  await solvent();

  const p = await lock(alice, "1000000000", 300);
  const quote = await pool.view("get_quote", { principal: p.principal, unlock_at: p.unlock_at });
  check("A 1000 TUSD source payout offers 650 with 663 due", () => { assert.equal(quote.maximum, "650000000"); assert.equal(quote.fee, "13000000"); assert.equal(quote.repay_amount, "663000000"); });
  const badQuote = await pledge(alice, p, { quote_nonce: "0" });
  check("A stale borrowing quote returns the original payout NFT", () => assert.equal(badQuote.accepted.parseResult(), false));
  assert.equal((await position(p.token_id)).owner_id, alice.accountId);
  const oversized = await pledge(alice, p, { amount: "651000000" });
  check("Borrowing above the collateral limit is rejected", () => assert.equal(oversized.accepted.parseResult(), false));
  const ready = await pledge(alice, p);
  assert.equal(ready.accepted.parseResult(), true);
  check("Accepted collateral reserves funded liquidity without moving principal", () => assert.equal(ready.loan.status, "CollateralReady"));
  assert.equal((await accounting()).reserved_loans, "650000000");
  assert.equal(await balance(alice), "0");
  assert.equal(await balance(vault), p.principal);
  await solvent();
  const theft = await send(bob, pool, "draw_loan", { loan_id: ready.loan.id });
  check("Only the collateral borrower can draw the reserved loan", () => assert.equal(theft.failed, true));
  const drawn = await send(alice, pool, "draw_loan", { loan_id: ready.loan.id });
  check("The borrower receives the actual 650 TUSD payment", () => assert.equal(drawn.parseResult(), true));
  assert.equal(await balance(alice), "650000000");
  assert.equal((await loan(ready.loan.id)).status, "Active");
  const held = await position(p.token_id);
  assert.equal(held.owner_id, pool.accountId); assert.equal(held.principal, p.principal); assert.equal(held.unlock_at, p.unlock_at);
  const repeatedDraw = await send(alice, pool, "draw_loan", { loan_id: ready.loan.id });
  check("A loan cannot disburse a second time", () => assert.equal(repeatedDraw.failed, true));
  await send(alice, market, "prepay_listing", {}, STORAGE);
  const doubleUse = await send(alice, vault, "nft_transfer_call", { receiver_id: market.accountId, token_id: p.token_id, msg: JSON.stringify({ price: "920000000" }) });
  check("Pledged collateral cannot also be listed for sale", () => assert.equal(doubleUse.failed, true));
  await send(bob, token, "ft_transfer", { receiver_id: alice.accountId, amount: "13000000" });
  const shortPayment = await repay(alice, ready.loan.id, "650000000");
  check("A partial repayment is returned without closing the loan", () => assert.equal(shortPayment.parseResult(), "0"));
  const otherPayment = await repay(bob, ready.loan.id, "663000000");
  check("Another account cannot repay and claim the collateral", () => assert.equal(otherPayment.parseResult(), "0"));
  assert.equal((await repay(alice, ready.loan.id, "663000000")).parseResult(), "663000000");
  check("Repayment records exactly the loan and its one-time fee", () => assert.equal((BigInt(ready.loan.amount) + BigInt(ready.loan.fee)).toString(), "663000000"));
  assert.equal((await loan(ready.loan.id)).status, "RepaymentReady");
  assert.equal((await position(p.token_id)).owner_id, pool.accountId);
  await send(alice, token, "faucet", {}, "0");
  const duplicateRepay = await repay(alice, ready.loan.id, "663000000");
  check("A repaid loan cannot take another repayment", () => assert.equal(duplicateRepay.parseResult(), "0"));
  const returned = await send(alice, pool, "release_collateral", { loan_id: ready.loan.id }, OPERATION_STORAGE);
  check("Repayment returns the same payout NFT with its original maturity", () => assert.equal(returned.parseResult(), true));
  assert.equal((await loan(ready.loan.id)).status, "Repaid");
  const after = await position(p.token_id);
  assert.equal(after.owner_id, alice.accountId); assert.equal(after.unlock_at, p.unlock_at); assert.equal(after.principal, p.principal);
  await solvent();

  const unpaid = await lock(alice, "1000000000", 60);
  const defaultLoan = await pledge(alice, unpaid);
  await send(alice, pool, "draw_loan", { loan_id: defaultLoan.loan.id });
  await send(bob, token, "ft_transfer", { receiver_id: alice.accountId, amount: "13000000" });
  const earlySettlement = await send(bob, pool, "settle_maturity", { loan_id: defaultLoan.loan.id });
  check("The pool cannot claim collateral before its original maturity", () => assert.equal(earlySettlement.failed, true));
  await worker.provider.fastForward(100);
  const late = await repay(alice, defaultLoan.loan.id, "663000000");
  check("A matured loan returns a late repayment for settlement review", () => assert.equal(late.parseResult(), "0"));
  const settled = await send(bob, pool, "settle_maturity", { loan_id: defaultLoan.loan.id });
  check("An unpaid loan receives its full actual source payout at maturity", () => assert.equal(settled.parseResult(), true));
  assert.equal((await position(unpaid.token_id)).status, "Redeemed");
  assert.equal((await loan(defaultLoan.loan.id)).status, "Settled");
  const creditedSurplus = (await pool.view("get_account", { account_id: alice.accountId })).surplus;
  const settlementAccounting = await accounting();
  check("The pool keeps 663 and credits the remaining 337 to the borrower", () => { assert.equal(defaultLoan.loan.repay_amount, "663000000"); assert.equal(creditedSurplus, "337000000"); assert.equal(settlementAccounting.total_settled, "663000000"); });
  const repeatSettlement = await send(alice, pool, "settle_maturity", { loan_id: defaultLoan.loan.id });
  check("Maturity settlement cannot run twice", () => assert.equal(repeatSettlement.failed, true));
  await solvent();
  const beforeSurplus = BigInt(await balance(alice));
  await send(alice, pool, "withdraw_surplus", {});
  const afterSurplus = BigInt(await balance(alice));
  check("The borrower receives the actual 337 TUSD remaining payout", () => assert.equal(afterSurplus - beforeSurplus, 337000000n));
  const repeatSurplus = await send(alice, pool, "withdraw_surplus", {});
  check("A withdrawn collateral surplus cannot be withdrawn again", () => assert.equal(repeatSurplus.failed, true));
  await solvent();

  const cancellable = await lock(alice, "100000000", 300);
  const undrawn = await pledge(alice, cancellable);
  const priorLiquidity = BigInt((await accounting()).available_liquidity);
  const cancelled = await send(alice, pool, "cancel_collateral", { loan_id: undrawn.loan.id }, OPERATION_STORAGE);
  check("An undrawn loan returns collateral and releases reserved liquidity", () => assert.equal(cancelled.parseResult(), true));
  assert.equal((await position(cancellable.token_id)).owner_id, alice.accountId);
  assert.equal(BigInt((await accounting()).available_liquidity) - priorLiquidity, 65000000n);
  await solvent();

  const unsupportedWallet = await lock(alice, "100000000", 300);
  await send(alice, vault, "nft_transfer", { receiver_id: stranger.accountId, token_id: unsupportedWallet.token_id });
  await send(stranger, pool, "register_account", {}, STORAGE);
  const unable = await pledge(stranger, { ...unsupportedWallet, owner_id: stranger.accountId });
  const failedPayout = await send(stranger, pool, "draw_loan", { loan_id: unable.loan.id });
  check("A failed token payout preserves undrawn collateral and reserved funds", () => assert.equal(failedPayout.parseResult(), false));
  assert.equal((await loan(unable.loan.id)).status, "CollateralReady");
  await solvent();
  await send(stranger, pool, "cancel_collateral", { loan_id: unable.loan.id }, OPERATION_STORAGE);
  assert.equal((await position(unsupportedWallet.token_id)).owner_id, stranger.accountId);
  await solvent();

  const final = await accounting();
  check("Completed loan accounting remains solvent with no reserved or pending funds", () => { assert.equal(final.reserved_loans, "0"); assert.equal(final.outstanding_principal, "0"); assert.equal(final.borrower_surplus, "0"); assert.equal(final.pending_withdrawals, "0"); });
  await mkdir(join(project, "docs/evidence"), { recursive: true });
  await writeFile(join(project, "docs/evidence/lending-tests.json"), JSON.stringify({ status: "PASS", checkedAt: new Date().toISOString(), network: "isolated local NEAR Sandbox", checks, accounting: final, contracts: { source: vault.accountId, pool: pool.accountId, token: token.accountId }, original: p, repaidPosition: after, receipts: receipts.map(result => ({ hash: result.transaction.hash, signer: result.transaction.signer_id, receiver: result.transaction.receiver_id, status: result.status })) }, null, 2) + "\n");
  console.log(`LENDING PASS: ${checks.length} behaviors; real funded-pool borrowing, repayment, maturity surplus, recovery and solvency.`);
} finally { await sandbox.close(); }
